"""Reports contain measurements only; no claims of product or real-world efficacy."""
from pipeline.io import read, write

DISCLAIMER = "본 환경은 HTTP 응답 개인정보 검출 이벤트를 모사하는 연구용 시험환경이며, 상용 WAF나 상용 개인정보 접속기록 솔루션을 평가하지 않는다."

def table(records, columns):
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join(["---"] * len(columns)) + " |"]
    for row in records:
        lines.append("| " + " | ".join(str(row.get(c, "—")) for c in columns) + " |")
    return "\n".join(lines)

def report(run):
    output = run / "report.md"
    if output.exists():
        raise FileExistsError(output)
    cfg = read(run / "config.json")
    pop = read(run / "population_summary.json")
    summary = read(run / "scenario_summary.json")
    text = ["# Synthetic HTTP disclosure experiment", "", DISCLAIMER, "",
            "취약 동작을 포함한 로컬 합성 연구 환경. 실제 개인정보·기관 로그를 사용하지 않았다. "
            "실시간 차단, 상용 제품 성능, 법적 유출 판단, 운영망 성능 또는 일반화 효과를 입증하지 않는다.",
            "", f"Seed: {cfg['seed']}; mode: {summary['mode']}.",
            f"Planned incidents: {summary['planned_incidents']}; planned responses: {summary['planned_responses']}; actual responses: {summary['actual_responses']}.",
            "", "## Populations", "", table([{"item": k, "value": v} for k, v in pop.items()], ["item", "value"]),
            "", "All responses are retained privately. Primary comparisons use the same detector-positive responses; U is excluded, never converted to 0.",
            "Detector coverage above is separate from classifier performance below. No improvement is presumed.",
            "", "## Protocol", "",
            "D0=response-only; D1=D0+web/session; D2=D1+application audit observations. No policy table is provided to models.",
            "R0/R1/R2 use configured weighted scores. M0/M1/M2 use one logistic-regression configuration each, fitted on train only.",
            "Incident spans that overlap are merged, then split chronologically by whole blocks. Split manifest: splits.json.",
            f"Decision time: detector event + {cfg['decision_delay_seconds']} seconds; only already ingested and non-future events are usable.",
            "Reproducible synthetic event times are generated by the server request counter. Wall-clock durations and response receipt time are separately measured.",
            f"Validation target alert rate: {cfg['target_alert_rate']}. Threshold maximizes attainable alert count without exceeding budget.",
            "All tied scores cross the threshold together; a tied group is excluded if it would exceed budget. No test-budget re-ranking.",
            "Average precision uses sklearn.average_precision_score (recall-increment weighted precision), not trapezoidal PR-AUC.",
            "Undefined precision is null when there are no alerts; a one-class test set has unavailable metrics.",
            "Incident hit requires an alert on a truly positive response. First detection counts observed primary-population responses from incident start; undetected incidents remain censored.",
            "Bootstrap: paired incident clusters, same resamples for every comparison; skip one-class resamples; percentile 95% CI for F1 differences.",
            "", "## Measured conditions", ""]
    for dest in sorted((run / "versions").iterdir()):
        if not (dest / "evaluation.json").exists():
            continue
        result = read(dest / "evaluation.json")
        training = read(dest / "training.json")
        features = read(dest / "feature_metadata.json")
        boot = read(dest / "bootstrap.json")
        text += [f"### {dest.name}", "", table([{"model": k, **v, "threshold": training[k]["threshold"]} for k, v in result.items()],
            ["model", "status", "n", "precision", "recall", "F1", "false_positive_rate", "average_precision", "alert_rate", "threshold", "incident_detection_rate"]),
            "", table([{"model": k, **v} for k, v in training.items()],
            ["model", "fit_seconds", "inference_seconds", "validation_alert_rate"]),
            "", table([{"item": k, "value": features[k]} for k in ("rows", "feature_seconds", "web_missing_rate", "audit_missing_rate",
                       "link_success_rate", "link_precision", "link_recall", "link_states")], ["item", "value"]),
            "", table([{"comparison": k, **v} for k, v in boot.get("pairs", {}).items()] if isinstance(boot.get("pairs"), dict) else [],
                       ["comparison", "metric", "observed_difference", "ci95", "valid_resamples"]),
            "", f"Bootstrap iterations: {cfg['bootstrap_iterations']}; one-class resamples skipped: {boot.get('skipped_one_class', 'unavailable')}.",
            "", f"Feature lists/counts: versions/{dest.name}/feature_metadata.json. PR curves, confusion matrices: figures/ and CSV files.",
            f"U excluded on test: { {k: v['excluded_U_test'] for k, v in result.items()} }.", ""]
    text += ["## Limits", "", "Small smoke samples verify software integration only, not statistical sufficiency. "
             "All relationships, tasks, timing and defects are synthetic. JSON-key-dependent detection misses renamed fields; "
             "the independent oracle can match those values. The oracle only recognizes known full or configured masked values, "
             "not arbitrary encodings, substrings, images or transformed text. Application audit logs are not database-engine audit logs.",
             "Withheld snapshots and simulated evidence loss intentionally create U. Raw received response evidence is preserved separately.",
             "No gain, zero gain or worse results must all be reported as measured. Broader seeds and sensitivity studies remain necessary.",
             "", "Exact dependency versions and platform: environment.json. Source configuration: config.json. "
             "Raw responses/ground truth: private/. Model inputs contain only whitelisted features in versions/*/inputs/.", ""]
    output.write_text("\n".join(text), encoding="utf-8")
    return output
